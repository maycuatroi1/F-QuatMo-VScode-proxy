import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { Hono } from "hono";

assert.equal(process.env.PROXY_REFACTOR_SANDBOX, "1");
assert.equal(process.cwd(), process.env.PROXY_RELEASE_ROOT);
assert.ok(fs.existsSync(path.join(process.cwd(), ".release-test-fixture")));
const { updateRouter, saveReleaseManifest, getCurrentRelease } = await import("../../src/routes/update");
const { s3Storage } = await import("../../src/services/s3Storage");
const app = new Hono();
app.route("/v1", updateRouter);
app.route("/", updateRouter);
s3Storage.isAvailable = () => false;
s3Storage.listAllReleaseObjects = async () => [];
const master = { Authorization: `Bearer ${process.env.PROXY_API_KEY}`, "Content-Type": "application/json" };
const base = { version: "1.0.0", commit: "new-commit", updateType: "installer" as const, filename: "fixture.exe", downloadUrl: "", releasedAt: "2026-01-01T00:00:00Z", mandatory: false, sha256hash: "f".repeat(64) };
const scenario = process.argv[2];

if (scenario === "native") {
  saveReleaseManifest(base);
  assert.equal((await app.request("/v1/api/update/win32-x64-user/stable/NEW-COMMIT")).status, 204);
  const newer = await app.request("/v1/api/update/win32-x64-user/stable/old-commit?bg=true", { headers: { Host: "untrusted.example" } });
  assert.equal(newer.status, 200);
  assert.deepEqual(await newer.json(), { url: "https://proxy.example.test/v1/releases/fixture.exe", name: "Fvscode 1.0.0", version: "new-commit", productVersion: "1.0.0", sha256hash: "f".repeat(64) });
  saveReleaseManifest({ ...base, version: "1.1.0", commit: "patch-commit", updateType: "patch" });
  // A patch-only latest app state is not offered as a native installer.
  assert.equal((await app.request("/v1/api/update/win32-x64-user/stable/old-commit")).status, 204);
  const current = await (await app.request("/release/current")).json();
  assert.equal(current.release.commit, "patch-commit");
  assert.equal(current.release.downloadUrl, "https://proxy.example.test/v1/releases/fixture.exe");
  assert.equal(current.s3Enabled, false);
  const bytes = Buffer.from([0, 255, 1, 80, 75]);
  fs.writeFileSync(path.join(process.cwd(), "releases", "fixture.bin"), bytes);
  const artifact = await app.request("/v1/releases/fixture.bin");
  assert.equal(artifact.status, 200);
  assert.equal(artifact.headers.get("Content-Disposition"), 'attachment; filename="fixture.bin"');
  assert.deepEqual(Buffer.from(await artifact.arrayBuffer()), bytes);
  assert.equal((await app.request("/v1/releases/missing.bin")).status, 404);
  s3Storage.isAvailable = () => true;
  s3Storage.getReleaseStream = async () => ({ stream: new ReadableStream({ start(c) { c.enqueue(bytes); c.close(); } }), contentType: "application/octet-stream", contentLength: bytes.length });
  const remote = await app.request("/v1/releases/remote.bin");
  assert.equal(remote.status, 200);
  assert.deepEqual(Buffer.from(await remote.arrayBuffer()), bytes);
} else if (scenario === "publication") {
  const publish = (body: object, headers = master) => app.request("/v1/release/set-latest", { method: "POST", headers, body: JSON.stringify(body) });
  assert.equal((await publish(base, {} as typeof master)).status, 401);
  assert.equal((await publish({})).status, 400);
  assert.equal((await publish({ ...base, downloadUrl: "https://not-allowed.test/installer.exe" })).status, 400);
  assert.equal((await publish({ ...base, sha256hash: "invalid" })).status, 400);
  const response = await publish({ ...base, targetExtensionId: "previous.extension", downloadUrl: "https://cdn.example.test/fixture.exe" });
  assert.equal(response.status, 200);
  const published = (await response.json()).release;
  assert.equal(published.commit, "new-commit");
  assert.equal(published.downloadUrl, "https://cdn.example.test/fixture.exe");
  assert.equal(JSON.parse(fs.readFileSync(path.join(process.cwd(), "release_manifest.json"), "utf8")).commit, "new-commit");
  let reads = 0;
  const signed = { ...base, commit: "signed-commit", version: "2.0.0", downloadUrl: "https://cdn.example.test/signed.exe", signature: "ed25519:synthetic-fixture" };
  s3Storage.isAvailable = () => true;
  s3Storage.getReleaseManifestFromS3 = async () => { reads++; return signed; };
  const synced = await (await app.request("/release/sync-s3", { method: "POST" })).json();
  assert.equal(synced.release.commit, "signed-commit");
  assert.equal(synced.release.targetExtensionId, undefined);
  assert.equal(synced.release.signature, signed.signature);
  await app.request("/release/sync-s3", { method: "POST" });
  assert.equal(reads, 1);
  assert.equal(getCurrentRelease().commit, "signed-commit");
} else assert.fail("Unknown release probe");
console.log(`RELEASE_PROBE:${scenario}:PASS`);
